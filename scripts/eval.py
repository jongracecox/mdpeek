"""Measure how much context mdpeek saves compared with reading a whole file.

Runs each scenario in evals/scenarios.toml (a question, the mdpeek calls an
agent would make, and text the answer must contain) and counts the
characters those calls print, stdout and stderr together, since both reach
an agent. Tokens are estimated as characters / 4, which is deterministic and
close enough to compare runs.

    uv run python scripts/eval.py                    # print and write evals/report.md
    uv run python scripts/eval.py --check            # fail on a regression (CI)
    uv run python scripts/eval.py --update-baseline  # accept the current numbers
"""

from __future__ import annotations

import argparse
import contextlib
import io
import json
import math
import sys
from dataclasses import dataclass
from pathlib import Path

import tomllib

from mdpeek.cli import main as mdpeek

ROOT = Path(__file__).resolve().parent.parent
SCENARIOS = ROOT / "evals" / "scenarios.toml"
BASELINE = ROOT / "evals" / "baseline.json"
REPORT = ROOT / "evals" / "report.md"
TOLERANCE = 0.10
"""How much worse (relative) a scenario may get before --check fails."""


def tokens(chars: int) -> int:
    return math.ceil(chars / 4)


@dataclass
class Outcome:
    name: str
    question: str
    steps: int
    chars: int
    found: bool
    failures: list[str]

    @property
    def tokens(self) -> int:
        return tokens(self.chars)


def run_step(document: Path, args: list[str]) -> tuple[int, str, str]:
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            code = mdpeek([str(document), *args])
        except SystemExit as exc:  # argparse errors
            code = exc.code if isinstance(exc.code, int) else 1
    return code, out.getvalue(), err.getvalue()


def run_scenario(document: Path, scenario: dict) -> Outcome:
    chars, failures, last = 0, [], ""
    for args in scenario["steps"]:
        code, out, err = run_step(document, args)
        chars += len(out) + len(err)
        last = out
        if code != 0:
            failures.append(f"`mdpeek {' '.join(args)}` exited {code}: {err.strip()}")
    found = scenario["expect"] in last
    if not found:
        failures.append(f"final output does not contain {scenario['expect']!r}")
    return Outcome(
        scenario["name"], scenario["question"], len(scenario["steps"]), chars, found, failures
    )


def report(document: Path, full_chars: int, outcomes: list[Outcome]) -> str:
    full = tokens(full_chars)
    lines = [
        "# mdpeek efficiency report",
        "",
        f"Generated by `scripts/eval.py` from `evals/scenarios.toml`. Document: "
        f"`{document.relative_to(ROOT)}`, {full_chars:,} characters (~{full:,} tokens "
        "if read whole). Tokens are estimated as characters / 4.",
        "",
        "Each scenario's calls are scripted, so these are best-case numbers: a real "
        "agent may make extra or exploratory calls, but still never pays for the "
        "parts of the document it doesn't open.",
        "",
        "| Scenario | Question | Calls | ~Tokens | vs whole file | Answer |",
        "|---|---|---|---|---|---|",
    ]
    for o in outcomes:
        share = 100 * o.tokens / full
        answer = "found" if o.found else "**missing**"
        lines.append(
            f"| {o.name} | {o.question} | {o.steps} | {o.tokens:,} | {share:.1f}% | {answer} |"
        )
    total = sum(o.tokens for o in outcomes)
    lines += [
        "",
        f"All {len(outcomes)} scenarios together: ~{total:,} tokens, "
        f"{100 * total / (full * len(outcomes)):.1f}% of reading the whole file "
        f"once per question (~{full * len(outcomes):,} tokens).",
        "",
    ]
    return "\n".join(lines)


def check(outcomes: list[Outcome], baseline: dict[str, int]) -> list[str]:
    problems = [f"{o.name}: {f}" for o in outcomes for f in o.failures]
    for o in outcomes:
        if o.name not in baseline:
            problems.append(f"{o.name}: not in {BASELINE.name}; run --update-baseline")
        elif o.tokens > baseline[o.name] * (1 + TOLERANCE):
            problems.append(
                f"{o.name}: ~{o.tokens} tokens, more than {TOLERANCE:.0%} above "
                f"the baseline of {baseline[o.name]}"
            )
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail on regressions (for CI)")
    mode.add_argument("--update-baseline", action="store_true", help="accept current numbers")
    args = parser.parse_args()

    config = tomllib.loads(SCENARIOS.read_text(encoding="utf-8"))
    document = ROOT / config["document"]
    full_chars = len(document.read_text(encoding="utf-8"))
    outcomes = [run_scenario(document, s) for s in config["scenario"]]
    text = report(document, full_chars, outcomes)
    print(text)

    if args.check:
        baseline = json.loads(BASELINE.read_text(encoding="utf-8"))
        problems = check(outcomes, baseline)
        for problem in problems:
            print(f"eval: {problem}", file=sys.stderr)
        return 1 if problems else 0

    REPORT.write_text(text, encoding="utf-8")
    if args.update_baseline:
        failed = [f"{o.name}: {f}" for o in outcomes for f in o.failures]
        if failed:
            print("\n".join(f"eval: {f}" for f in failed), file=sys.stderr)
            return 1
        BASELINE.write_text(
            json.dumps({o.name: o.tokens for o in outcomes}, indent=2) + "\n", encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
